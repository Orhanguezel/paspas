CREATE TABLE IF NOT EXISTS `contact_messages` (
  `id` char(36) NOT NULL,
  `reference_no` varchar(32) NOT NULL,
  `idempotency_key` varchar(80) DEFAULT NULL,
  `name` varchar(160) NOT NULL,
  `email` varchar(191) DEFAULT NULL,
  `phone` varchar(64) NOT NULL,
  `subject` varchar(191) DEFAULT NULL,
  `message` text,
  `status` enum('new','in_progress','closed') NOT NULL DEFAULT 'new',
  `is_resolved` tinyint(1) NOT NULL DEFAULT 0,
  `assigned_to_user_id` char(36) DEFAULT NULL,
  `admin_note` text,
  `ip` varchar(64) DEFAULT NULL,
  `user_agent` varchar(255) DEFAULT NULL,
  `website` varchar(255) DEFAULT NULL,
  `locale` varchar(8) DEFAULT NULL,
  `source_page` varchar(512) DEFAULT NULL,
  `kvkk_accepted_at` datetime DEFAULT NULL,
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`), UNIQUE KEY `uq_contact_reference` (`reference_no`),
  UNIQUE KEY `uq_contact_idempotency` (`idempotency_key`),
  KEY `idx_contact_status_created` (`status`,`created_at`),
  KEY `idx_contact_ip_created` (`ip`,`created_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
